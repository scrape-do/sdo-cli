// Command apisurface prints the sdo CLI's compatibility surface — every
// command, positional argument and flag, and every MCP tool and its input
// parameters — one symbol per line, sorted:
//
//	install sdo github.com/scrape-do/sdo-cli/cmd/sdo
//	command sdo.jobs.result
//	arg sdo.jobs.result #0 jobID [required]
//	flag sdo.scrape --header -H stringArray
//	mcp-tool scrape
//	mcp-param scrape url string [required]
//
// No help prose and no versions: wording and releases are not API. A line that
// disappears is a breaking change; a new "[required]" line on an existing
// command or tool is one too. Regenerate the golden with:
//
//	go run ./tools/apisurface > api-surface.txt
package main

import (
	"context"
	"fmt"
	"path"
	"sort"
	"strings"

	"github.com/scrape-do/sdo-cli/cmd"
	"github.com/scrape-do/sdo-cli/internal/mcp"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const header = "# sdo CLI + MCP compatibility surface. Generated by tools/apisurface -- DO NOT EDIT.\n" +
	"# Regenerate: go run ./tools/apisurface > api-surface.txt\n"

func main() {
	fmt.Print(render())
}

// installPath is the package `go install` builds the sdo binary from. Go
// names the binary after its last element, so it is part of the contract:
// moving it changes what users type and what their binary is called.
const installPath = "github.com/scrape-do/sdo-cli/cmd/sdo"

func render() string {
	lines := append(commandLines(cmd.NewRootCommand()), mcpLines()...)
	lines = append(lines, "install "+path.Base(installPath)+" "+installPath)
	sort.Strings(lines)
	return header + strings.Join(lines, "\n") + "\n"
}

// commandLines walks the cobra tree, including the help and completion
// commands cobra adds when the CLI runs.
func commandLines(root *cobra.Command) []string {
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	root.InitDefaultVersionFlag()
	var lines []string
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		if c.Hidden {
			return
		}
		owner := strings.ReplaceAll(c.CommandPath(), " ", ".")
		lines = append(lines, "command "+owner)
		for i, arg := range strings.Fields(c.Use)[1:] {
			lines = append(lines, argLine(owner, i, arg))
		}
		c.LocalFlags().VisitAll(func(f *pflag.Flag) {
			if f.Name != "help" && !f.Hidden { // --help is implicit on every command
				lines = append(lines, flagLine(owner, f))
			}
		})
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
	return lines
}

// argLine renders a positional argument from the usage string: <name> is
// required, [name] or [name...] is optional.
func argLine(owner string, pos int, arg string) string {
	required := strings.HasPrefix(arg, "<")
	name := strings.Trim(arg, "<>[]")
	line := fmt.Sprintf("arg %s #%d %s", owner, pos, name)
	if required {
		line += " [required]"
	}
	return line
}

func flagLine(owner string, f *pflag.Flag) string {
	line := fmt.Sprintf("flag %s --%s", owner, f.Name)
	if f.Shorthand != "" {
		line += " -" + f.Shorthand
	}
	line += " " + f.Value.Type()
	switch f.DefValue {
	case "", "false", "0", "[]":
	default:
		line += " default=" + f.DefValue
	}
	return line
}

// mcpLines reads the tool list the server actually serves.
func mcpLines() []string {
	resp := mcp.Handle(context.Background(), nil, &mcp.Request{JSONRPC: "2.0", ID: []byte("1"), Method: "tools/list"})
	var lines []string
	for _, tool := range resp.Result.(map[string]any)["tools"].([]map[string]any) {
		name := tool["name"].(string)
		lines = append(lines, "mcp-tool "+name)
		schema := tool["inputSchema"].(map[string]any)
		required := map[string]bool{}
		for _, r := range schema["required"].([]string) {
			required[r] = true
		}
		for param, def := range schema["properties"].(map[string]any) {
			d := def.(map[string]any)
			line := fmt.Sprintf("mcp-param %s %s %s", name, param, d["type"])
			if enum, ok := d["enum"].([]string); ok {
				line += " enum=" + strings.Join(enum, "|")
			}
			if required[param] {
				line += " [required]"
			}
			lines = append(lines, line)
		}
	}
	return lines
}
